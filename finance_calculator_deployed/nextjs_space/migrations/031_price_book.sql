-- Migration: editable surcharge price book (cennik dopłat), per steel type.
-- Run this manually with: psql $DATABASE_URL -f migrations/031_price_book.sql
--
-- Kontekst: every surcharge number of the calculator used to be hardcoded in
-- lib/calculatorData.ts. From v2.0 the superuser edits them at /admin/cennik.
--   * price_book_entries - OVERRIDES ONLY. The effective book = code defaults + these rows
--     (lib/priceBook.ts mergePriceBook). A value set back to its default deletes the row.
--     Keys address cells of the code structure: table_key in (option, dimension, coating,
--     baseLength, baseWidth, pickling, teardrop, scalar), row_key/col_key e.g.
--     ('option', 'sscEdging', '1') or ('dimension', '3.00-3.99', '1100-1499').
--   * steel_grades - the grade list per type (replaces GRADE_TABLE_* + YIELD_GRADES), seeded
--     below from the code tables. Grades are retired (retired_at), never deleted, so old
--     offers referring to them still open and print.
--   * price_book_log - one row per changed value (who, when, old -> new).
-- Until this migration runs, GET /api/price-book serves the code defaults (42P01 fallback)
-- and saving from the panel is refused with a clear message.

SET client_encoding = 'UTF8';

BEGIN;

CREATE TABLE IF NOT EXISTS price_book_entries (
    steel_type TEXT NOT NULL CHECK (steel_type IN ('HRS', 'CR', 'HDG', 'PICKLED', 'TEARDROP', 'ZM')),
    table_key  TEXT NOT NULL CHECK (table_key IN (
        'option', 'dimension', 'coating', 'baseLength', 'baseWidth', 'pickling', 'teardrop', 'scalar'
    )),
    row_key    TEXT NOT NULL,
    col_key    TEXT NOT NULL,
    value      NUMERIC(10,2) NOT NULL CHECK (value BETWEEN -1000 AND 5000),
    updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (steel_type, table_key, row_key, col_key)
);

CREATE TABLE IF NOT EXISTS steel_grades (
    id                  SERIAL PRIMARY KEY,
    steel_type          TEXT NOT NULL CHECK (steel_type IN ('HRS', 'CR', 'HDG', 'PICKLED', 'TEARDROP', 'ZM')),
    name                TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    surcharge           NUMERIC(10,2) NOT NULL CHECK (surcharge BETWEEN -1000 AND 5000),
    has_yield_surcharge BOOLEAN NOT NULL DEFAULT FALSE,
    retired_at          TIMESTAMP WITH TIME ZONE NULL,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (steel_type, name)
);

-- Grade names are unique per type regardless of case / surrounding spaces (same rule as the
-- API validation), so 'S355' and 's355' can never coexist even when inserted by hand.
CREATE UNIQUE INDEX IF NOT EXISTS uq_steel_grades_type_name_ci ON steel_grades (steel_type, lower(btrim(name)));

CREATE TABLE IF NOT EXISTS price_book_log (
    id         SERIAL PRIMARY KEY,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    steel_type TEXT NOT NULL CHECK (steel_type IN ('HRS', 'CR', 'HDG', 'PICKLED', 'TEARDROP', 'ZM')),
    table_key  TEXT NULL,
    row_key    TEXT NULL,
    col_key    TEXT NULL,
    grade_name TEXT NULL,
    old_value  NUMERIC(10,2) NULL,
    new_value  NUMERIC(10,2) NULL,
    action     TEXT NOT NULL CHECK (action IN (
        'set', 'reset', 'grade_add', 'grade_surcharge', 'grade_yield', 'grade_retire', 'grade_restore'
    ))
);

-- The panel always reads the newest rows first (last 200, optionally one type).
CREATE INDEX IF NOT EXISTS idx_price_book_log_changed_at ON price_book_log (changed_at DESC, id DESC);

